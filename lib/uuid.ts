/**
 * UUID v4. `crypto.randomUUID` bestaat alleen in een beveiligde context (https of localhost);
 * op het lokale netwerk via http (bijv. de telefoon op http://192.168.x.x:3000) valt deze terug
 * op `crypto.getRandomValues`, dat overal werkt.
 */
export function uuid(): string {
  if (typeof crypto.randomUUID === "function") return crypto.randomUUID();
  const b = crypto.getRandomValues(new Uint8Array(16));
  b[6] = (b[6] & 0x0f) | 0x40; // versie 4
  b[8] = (b[8] & 0x3f) | 0x80; // variant 10
  const h = [...b].map((x) => x.toString(16).padStart(2, "0")).join("");
  return `${h.slice(0, 8)}-${h.slice(8, 12)}-${h.slice(12, 16)}-${h.slice(16, 20)}-${h.slice(20)}`;
}
